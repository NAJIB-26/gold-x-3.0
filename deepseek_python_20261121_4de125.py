@st.cache_data(ttl=1800)  # تحديث كل 30 دقيقة
def _fetch_rss(url):
    """جلب feed واحد"""
    try:
        feed = feedparser.parse(url)
        items = []
        for entry in feed.entries[:6]:
            items.append({
                'title': entry.get('title', 'بدون عنوان'),
                'summary': entry.get('summary', '')[:300],
                'link': entry.get('link', '#'),
                'date': entry.get('published', '')
            })
        return items
    except Exception:
        return None


@st.cache_data(ttl=1800)
def get_news(category):
    """جلب أخبار فئة معينة مع fallback"""
    info = FEEDS.get(category)
    if not info:
        return []
    
    for url in info['sources']:
        items = _fetch_rss(url)
        if items:
            return items
    
    return info.get('fallback', [])


@st.cache_data(ttl=1800)
def is_live(category):
    """هل الأخبار حية أم احتياطية؟"""
    info = FEEDS.get(category)
    if not info:
        return False
    for url in info['sources']:
        if _fetch_rss(url):
            return True
    return False